"""TF-4 test of CWO-1COR-05 in cwo_sweep_1cor.py: the eleven plant fixtures of the E3 reference (cwo05_ref.py, sha
efaa7c0d, regenerated by its author after the scratchpad purge and digest-equal), each run through the sweep itself as a
row, and equality of the sweep's hits with the reference's on the rows given. Writes only under --work.
usage: test_cwo05.py SWEEP.py ROWS.jsonl --work DIR
"""
import json
import os
import subprocess
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
REF = HERE / "cwo05_ref.py"
PLANTS = [("The RP pilcrow at 1:10 opens the unit.", True), ("The RP pilcrow at 15:35 closes the argument.", True),
          ("The RP pilcrow at 14:34 decides the seam.", True), ("The RP pilcrow drives the cut at 15:50.", True),
          ("Pilcrows open both units.", True), ("The pilcrow opens the unit and decides nothing.", True),
          ("RP pilcrow on the close seam (15:12)", False), ("The RP pilcrow at 10:14 informs and does not decide.", False),
          ("RP pilcrow at 16:13 (close seam).", False), ("The RP pilcrow at 1:10 marks the onset.", False),
          ("rp:1Cor.15.12 (conditional opens the following argument; RP pilcrow)", True)]


def run(*a):
    return subprocess.run([sys.executable, "-B", *map(str, a)], capture_output=True, text=True, encoding="utf-8",
                          env=dict(os.environ, PYTHONIOENCODING="utf-8"))   # the reference prints Greek before --out


def sweep(script, rows, out):
    p = run(script, rows, "--out", out)
    if p.returncode:
        raise SystemExit("sweep failed: " + p.stderr[-400:])
    return json.loads(Path(out).read_text(encoding="utf-8"))["CWO05"]


def key(h):
    return h["row"], h["field"], h["index"], h["text"]


sweep_py, rows_p, work = sys.argv[1], sys.argv[2], Path(sys.argv[sys.argv.index("--work") + 1])
work.mkdir(parents=True, exist_ok=True)
fails = []
ref_plants = run(REF, "--plants")
if ref_plants.returncode:
    fails.append("the reference fails its own plants")
plant_rows = work / "plants.jsonl"
# each plant is one whole unit, as the reference tests it: a ref element is not split at ';' (plant 11 is ref-shaped)
plant_rows.write_text("".join(json.dumps({"decision_id": "PLANT-%02d" % i, "span": "1Cor.1.1", "boundary_evidence_refs": [s]}, ensure_ascii=False) + "\n"
                              for i, (s, _) in enumerate(PLANTS, 1)), encoding="utf-8", newline="\n")
got = {h["row"] for h in sweep(sweep_py, plant_rows, work / "plants_out.json")["list"]}
for i, (s, want) in enumerate(PLANTS, 1):
    if (("PLANT-%02d" % i) in got) != want:
        fails.append("plant %d, want %s: %s" % (i, want, s))
ref_out = work / "ref_hits.json"
if run(REF, rows_p, "--out", ref_out).returncode:
    fails.append("the reference failed on the rows")
ref = json.loads(ref_out.read_text(encoding="utf-8"))
mine = sweep(sweep_py, rows_p, work / "rows_out.json")
if sorted(map(repr, map(key, ref))) != sorted(map(repr, map(key, mine["list"]))):
    fails.append("sweep hits differ from the reference")
print(json.dumps({"plants": len(PLANTS), "plants_hit": len(got), "reference_hits": len(ref), "sweep_hits": mine["hits"],
                  "sweep_rows": mine["rows"], "fails": fails, "verdict": "GREEN" if not fails else "RED"}, ensure_ascii=False))
sys.exit(1 if fails else 0)
